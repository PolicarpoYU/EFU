def conta_emojis_do_grupo(base, lista):
    total = 0
    unicos = set()
    vazios = 0

    if isinstance(base, str) and base.strip() != "":
        ems = quebra_emojis(base)
        total += len(ems)
        for e in ems:
            unicos.add(e)

    if isinstance(lista, list):
        for item in lista:
            if not isinstance(item, str):
                continue
            if item.strip() == "":
                vazios += 1
                continue
            ems = quebra_emojis(item)
            total += len(ems)
            for e in ems:
                unicos.add(e)

    return total, len(unicos), vazios
 
def imprime_qtd_emojis_por_grupo(Teclado_LIU, ordenar=False):
    dados_34 = []
    dados_menos = []

    for base, lista in Teclado_LIU.items():
        total = 0
        vazios = 0

        if not isinstance(lista, list):
            continue

        for item in lista:
            if isinstance(item, str) and item.strip() != "":
                total += 1
            else:
                vazios += 1

        registro = (base, total, vazios, len(lista))

        if total == 34:
            dados_34.append(registro)
        elif total < 34:
            dados_menos.append(registro)

    if ordenar:
        dados_34.sort(key=lambda x: x[0])
        dados_menos.sort(key=lambda x: (x[1], x[0]))

    print("GRUPOS COM 34 EMOJIS:\n")

    ct = 0
    soma_total = 0
    soma_vazios = 0

    for base, total, vazios, tamanho in dados_34:
        ct += 1
        soma_total += total
        soma_vazios += vazios
        print(f'{ct:3} | Grupo "{base}" -> emojis={total:3} | vazios={vazios:3} | lista={tamanho:3}')

    print("\nGRUPOS COM MENOS DE 34 EMOJIS:\n")

    for base, total, vazios, tamanho in dados_menos:
        ct += 1
        soma_total += total
        soma_vazios += vazios
        if total>9:
            print(f'{ct:3} | Grupo "{base}" -> emojis={total:3} | vazios={vazios:3} | lista={tamanho:3}')

    print("\nTOTAIS GERAIS:")
    print(f"grupos = {ct}")
    print(f"soma total de emojis = {soma_total}")
    print(f"soma total de vazios = {soma_vazios}")
