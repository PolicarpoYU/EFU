import re

def quebra_emojis(texto):
    padrao = re.compile(
        r'['
        r'\U0001F1E6-\U0001F1FF'
        r'\U0001F300-\U0001FAFF'
        r'\u2600-\u26FF'
        r'\u2700-\u27BF'
        r'](?:\uFE0F|\u200D['
        r'\U0001F300-\U0001FAFF'
        r'\u2600-\u26FF'
        r'\u2700-\u27BF'
        r'](?:\uFE0F)?)*',
        flags=re.UNICODE
    )
    return padrao.findall(texto)

def extrai_emojis_de_estrutura(obj):
    saida = []
    if isinstance(obj, str):
        saida.extend(quebra_emojis(obj))
    elif isinstance(obj, list) or isinstance(obj, tuple):
        for item in obj:
            saida.extend(extrai_emojis_de_estrutura(item))
    elif isinstance(obj, dict):
        for _, valor in obj.items():
            saida.extend(extrai_emojis_de_estrutura(valor))
    return saida

def extrai_emojis_teclado(teclado_liu):
    saida = []
    for base, lista in teclado_liu.items():
        if isinstance(base, str) and base != "":
            saida.extend(quebra_emojis(base))
        if isinstance(lista, list):
            for item in lista:
                if isinstance(item, str) and item != "":
                    saida.extend(quebra_emojis(item))
    return saida

