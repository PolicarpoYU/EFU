def padroniza_cor_teclado(cor_liu, Teclado_LIU, idx_cor=0, debug=False, listar_faltantes=False):
    faltantes = set()

    def cria_mapa_substituicao(cor_liu, idx_cor):
        mapa = {}
        for base, variantes in cor_liu.items():
            if not isinstance(variantes, list) or len(variantes) == 0:
                continue

            idx = max(0, min(idx_cor, len(variantes) - 1))
            alvo = variantes[idx]

            if not isinstance(alvo, str) or alvo.strip() == "":
                alvo = base

            mapa[base] = alvo

            for v in variantes:
                if isinstance(v, str) and v.strip() != "":
                    mapa[v] = alvo

        return mapa

    mapa_sub = cria_mapa_substituicao(cor_liu, idx_cor)
    novo = {}

    for base, lista in Teclado_LIU.items():
        nova_base = mapa_sub.get(base, base)
        if base not in mapa_sub and listar_faltantes and base not in ["", "‼️"]:
            faltantes.add(base)

        if not isinstance(lista, list):
            novo[nova_base] = lista
            continue

        nova_lista = []
        for item in lista:
            if not isinstance(item, str):
                nova_lista.append(item)
                continue

            item_novo = mapa_sub.get(item, item)
            nova_lista.append(item_novo)

            if item not in mapa_sub and listar_faltantes and item not in ["", "‼️"]:
                faltantes.add(item)

            if debug and item != item_novo:
                print(f"{item} -> {item_novo}")

        novo[nova_base] = nova_lista

    if listar_faltantes:
        return novo, sorted(faltantes)

    return novo

