def quebra_em_linhas(lista_emojis, num_colunas=7):
    linhas = []
    for i in range(0, len(lista_emojis), num_colunas):
        linhas.append(lista_emojis[i:i+num_colunas])
    return linhas

def resumo_teclado(teclado_liu, num_colunas=7):
    resumo = {}
    for grupo, lista_emojis in teclado_liu.items():
        linhas = quebra_em_linhas(lista_emojis, num_colunas)
        resumo[grupo] = {
            "total": len(lista_emojis),
            "linhas": len(linhas),
            "itens_por_linha": [len(l) for l in linhas],
            "conteudo": linhas
        }
    return resumo

def print_resumo_teclado(teclado_liu, num_colunas=7):
    resumo = resumo_teclado(teclado_liu, num_colunas)
    CT=0
    for grupo, info in resumo.items():
        CT+=1
        print(f"Grupo {grupo}:(Nunm={CT}, L={CT//7} C={CT%7+1})  total={info['total']} linhas={info['linhas']} itens/linha={info['itens_por_linha']}")
        for i, linha in enumerate(info["conteudo"], start=1):
            print(f"  linha {i}: {' '.join(linha)}")
        print()


def limita_teclado_liu(teclado_liu, max_linhas=77):
    teclado_out = {}

    for base, lista in teclado_liu.items():
        if not isinstance(lista, list):
            continue

        nova_lista = []
        vistos = set()

        for emoji in lista:
            emoji = emoji.strip()
            if emoji not in vistos:
                nova_lista.append(emoji)
                vistos.add(emoji)
            if len(nova_lista) >=max_linhas:
                break

        while len(nova_lista) < max_linhas:
            nova_lista.append("")

        teclado_out[base] = nova_lista

    return teclado_out


def converte_teclado_para_json_fixo(teclado_liu, max_linhas=77):
    teclado_limpo = limita_teclado_liu(teclado_liu, max_linhas=max_linhas)
    out = []

    for base, lista in teclado_limpo.items():
        registro = {"base": base}
        for i in range(max_linhas):
            chave = f"e{i+1:02d}"
            registro[chave] = lista[i]
        out.append(registro)

    return out


def save_teclado_liu_json(teclado_liu, file_name="Teclado_LIU.json", dir_db="./DB/", max_linhas=30):
    os.makedirs(dir_db, exist_ok=True)
    caminho = os.path.join(dir_db, file_name)

    dados = converte_teclado_para_json_fixo(teclado_liu, max_linhas=max_linhas)

    with open(caminho, "w", encoding="utf-8") as f:
        json.dump(dados, f, ensure_ascii=False, indent=2)

    print(f"Teclado LIU gravado em: {caminho}")
    return dados

def imprime_qtd_emojis_por_grupo(Teclado_LIU, ordenar=False):
    dados_34 = []
    dados_menos = []

    for base, lista in Teclado_LIU.items():
        total = 0
        vazios = 0

        if not isinstance(lista, list):
            continue

        for item in lista:
            if isinstance(item, str) and item.strip() != "":
                total += 1
            else:
                vazios += 1

        registro = (base, total, vazios, len(lista))

        if total == 34:
            dados_34.append(registro)
        elif total < 34:
            dados_menos.append(registro)

    if ordenar:
        dados_34.sort(key=lambda x: x[0])
        dados_menos.sort(key=lambda x: (x[1], x[0]))

    print("GRUPOS COM 34 EMOJIS:\n")

    ct = 0
    soma_total = 0
    soma_vazios = 0

    for base, total, vazios, tamanho in dados_34:
        ct += 1
        soma_total += total
        soma_vazios += vazios
        print(f'{ct:3} | Grupo "{base}" -> emojis={total:3} | vazios={vazios:3} | lista={tamanho:3}')

    print("\nGRUPOS COM MENOS DE 34 EMOJIS:\n")

    for base, total, vazios, tamanho in dados_menos:
        ct += 1
        soma_total += total
        soma_vazios += vazios
        if total>9:
            print(f'{ct:3} | Grupo "{base}" -> emojis={total:3} | vazios={vazios:3} | lista={tamanho:3}')

    print("\nTOTAIS GERAIS:")
    print(f"grupos = {ct}")
    print(f"soma total de emojis = {soma_total}")
    print(f"soma total de vazios = {soma_vazios}")
