def aplica_tom_simples(base,tom):
    if tom=="":
        return base
    return base+tom

def aplica_tom_composto(emoji,base_humano,tom):
    if tom=="":
        return emoji
    return emoji.replace(base_humano,base_humano+tom,1)

def gera_variantes_emoji(emoji):
    if emoji in MAP_COMPOSTOS:
        base_humana=MAP_COMPOSTOS[emoji]
        return [aplica_tom_composto(emoji,base_humana,tom) for tom in TONS]
    return [aplica_tom_simples(emoji,tom) for tom in TONS]

def adiciona_emoji(dic,emoji):
    if emoji in dic:
        return
    dic[emoji]=gera_variantes_emoji(emoji)

def expande_generos():
    out=[]
    for base,lista in VARIANTES_GENERO.items():
        for e in lista:
            out.append(e)
    return out

def gera_dic_cores():
    dic={}
    for e in BASES_SIMPLES:
        adiciona_emoji(dic,e)
    for e in expande_generos():
        adiciona_emoji(dic,e)
    for e in MAP_COMPOSTOS.keys():
        adiciona_emoji(dic,e)

    dic_ordenado={}
    for k in sorted(dic.keys()):
        dic_ordenado[k]=dic[k]
    return dic_ordenado

def grava_py(dic,file_name=file_name,dir_db=dir_db):
    os.makedirs(dir_db,exist_ok=True)
    path=os.path.join(dir_db,file_name)

    with open(path,"w",encoding="utf-8") as f:
        f.write("# Arquivo gerado automaticamente\n")
        f.write("cor_liu = {\n")
        itens=list(dic.items())
        for i,(k,v) in enumerate(itens):
            f.write(f'  {repr(k)}: {repr(v)}')
            if i < len(itens)-1:
                f.write(",\n")
            else:
                f.write("\n")
        f.write("}\n")
    return path

def main():
    dic=gera_dic_cores()
    path=grava_py(dic,file_name=file_name,dir_db=dir_db)
    print(f"Arquivo gerado: {path}")
    print(f"Total de emojis-base gravados: {len(dic)}")
    for k in list(dic.keys())[:20]:
        print(k,"=>",dic[k])

